export function detectKrvGrammarNotes(
	tokensByVerse: Array<{ verse: number; words: string[] }>,
): KrvGrammarNote[] {
	const found: KrvGrammarNote[] = [];

	for (const rule of KRV_GRAMMAR_RULES) {
		const verses = new Set<number>();
		const examples = new Set<string>();

		for (const item of tokensByVerse) {
			for (const word of item.words) {
				if (rule.matcher.test(word)) {
					verses.add(item.verse);
					if (examples.size < 3) examples.add(word);
				}
			}
		}

		if (verses.size > 0) {
			found.push({
				id: rule.id,
				pattern: rule.pattern,
				modern: rule.modern,
				explanation: rule.explanation,
				examples: [...examples],
				verses: [...verses].sort((a, b) => a - b),
			});
		}
	}

	return found;
}
